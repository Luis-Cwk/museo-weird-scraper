#!/usr/bin/env python3
"""
post-generate-patch.py — converts any voxel-N.html (generated by the old
generate-three.js with PlaneGeometry sky) into the canonical Huaca
look with CSS-background-sky + animated washes + scanlines + vignette.
Run after `agent.js` generates a new voxel.

The canonical look is the one Petra approved 2026-08-25:
  - Sky as CSS background, edge-to-edge
  - 12% wide wash left (cyan, moves up, 14s, blend: screen)
  - 12% wide wash right (dark blue, moves down, 18s, blend: multiply)
  - Voxel on transparent WebGL canvas
  - Vignette + scanlines (1.2% opacity, 3px drift, 8s)

Usage:
  python post-generate-patch.py <path-to-voxel-N.html>

The patch:
1. Extracts VOXEL, LAYOUT, PALETTE, META, SEED from the existing file
2. Rewrites the file with the canonical template
"""


#!/usr/bin/env python3
"""
post-generate-patch.py — converts any voxel-N.html (generated by the old
generate-three.js with PlaneGeometry sky) into the canonical Huaca
look with CSS-background-sky + animated washes + scanlines + vignette.
Run after `agent.js` generates a new voxel.

The canonical look is the one Petra approved 2026-08-25:
  - Sky as CSS background, edge-to-edge
  - 12% wide wash left (cyan, moves up, 14s, blend: screen)
  - 12% wide wash right (dark blue, moves down, 18s, blend: multiply)
  - Voxel on transparent WebGL canvas
  - Vignette + scanlines (1.2% opacity, 3px drift, 8s)

Usage:
  python post-generate-patch.py <path-to-voxel-N.html>

The patch:
1. Extracts VOXEL, LAYOUT, PALETTE, META, SEED from the existing file
2. Rewrites the file with the canonical template
"""

import re
import sys
import os


TEMPLATE = """<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Huaca, Sistemas Mágicos · {ID_SHORT}</title>
<style>
  /* === Huaca canonical look (rev 2026-08-26) ===
     Petra asked to remove the animated washes on the sides — they were
     too busy. The 2026-08-25 revision (sky + 12% wash-left + 12% wash-right +
     vignette + scanlines) is replaced by a single, clean sky background
     with the voxel on top. Only the HDRI (sky-bg) and the voxel layer remain.
  */
  html, body {{ margin: 0; padding: 0; height: 100%; overflow: hidden; font-family: ui-monospace, "Courier New", monospace; background: #000; }}
  #sky-bg {{
    position: fixed;
    top: 0; left: 0; right: 0; bottom: 0;
    width: 100%; height: 100%;
    background-image: url('{SKY_URL}');
    background-size: cover;
    background-position: center center;
    background-repeat: no-repeat;
    z-index: 1;
  }}
  #three-canvas {{
    position: fixed;
    top: 0; left: 0; right: 0; bottom: 0;
    width: 100%;
    height: 100%;
    z-index: 2;
    cursor: grab;
  }}
  #three-canvas:active {{ cursor: grabbing; }}
  .meta {{
    position: fixed;
    left: 14px;
    bottom: 10px;
    color: {ACCENT};
    font-size: 10px;
    letter-spacing: 3px;
    text-transform: uppercase;
    opacity: 0.85;
    pointer-events: none;
    z-index: 10;
  }}
  .meta.right {{ left: auto; right: 14px; bottom: 10px; }}
</style>
</head>
<body>
<div id="sky-bg"></div>
<canvas id="three-canvas"></canvas>
<div class="meta">{LABEL}</div>
<div class="meta right">№ {ID_SHORT_UPPER}</div>
<script type="importmap">
{{
  "imports": {{
    "three": "https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.js"
  }}
}}
</script>
<script type="module">
import * as THREE from 'three';

// Sky as CSS background, voxel on transparent WebGL canvas (no FOV/plane math).
const scene = new THREE.Scene();
const PALETTE = {PALETTE_LITERAL};
const VOXEL = {VOXEL_LITERAL};
const LAYOUT = {LAYOUT_LITERAL};
const META = {META_LITERAL};
const SEED = {SEED_LITERAL};

const sculptureWidth = VOXEL.width * LAYOUT.cellSize;
const sculptureHeight = VOXEL.height * LAYOUT.cellSize;
const fovRad = 50 * Math.PI / 180;
const margin = 1.5;
let camDist = 0;

const camera = new THREE.PerspectiveCamera(50, window.innerWidth / window.innerHeight, 0.1, 500);
const canvas = document.getElementById('three-canvas');
const renderer = new THREE.WebGLRenderer({{ canvas, antialias: true, alpha: true, preserveDrawingBuffer: true }});
renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.5));
renderer.setSize(window.innerWidth, window.innerHeight);
renderer.setClearColor(0x000000, 0);

const light = new THREE.PointLight(0xffffff, 2, 0, 0);
camera.add(light);
scene.add(camera);
scene.add(new THREE.AmbientLight(0xffffff, 0.55));
const sun = new THREE.DirectionalLight(0xffffff, 1.2);
sun.position.set(5, 10, 7);
scene.add(sun);
const fill = new THREE.DirectionalLight(0xfff5e8, 0.4);
fill.position.set(-5, 3, -5);
scene.add(fill);

const voxelGeom = new THREE.BoxGeometry(LAYOUT.cellSize, LAYOUT.cellSize, LAYOUT.cellSize);
const voxelMat = new THREE.MeshStandardMaterial({{ color: 0xf5f0e8, roughness: 0.5, metalness: 0.0 }});
const voxelMesh = new THREE.InstancedMesh(voxelGeom, voxelMat, LAYOUT.voxelCount);
const m = new THREE.Matrix4();
let i = 0;
for (const p of VOXEL.pixels) {{
  for (let d = 0; d < LAYOUT.depth; d++) {{
    if (i >= LAYOUT.voxelCount) break;
    m.makeTranslation(
      LAYOUT.centerX + p.x * LAYOUT.cellSize,
      LAYOUT.centerY - p.y * LAYOUT.cellSize,
      LAYOUT.centerZ + (d - LAYOUT.depth / 2) * LAYOUT.cellSize,
    );
    voxelMesh.setMatrixAt(i++, m);
  }}
}}
voxelMesh.count = i;
scene.add(voxelMesh);

let camDistMin = 4;
let camDistMax = 40;

function fitToViewport() {{
  const w = window.innerWidth;
  const h = window.innerHeight;
  // ?thumb=1: gallery card thumbnails. Use generous margin (1.5x) so the
  // voxel doesn't dominate the small frame. The auto-fit distance is also
  // clamped higher so the mesh stays centered.
  // Fullscreen keeps 1.5x breathing room; sub-600px thumbnails also get 1.5x
  // because the old 0.8 made the voxel spill off-frame in gallery cards.
  const isThumb = /[?&]thumb=1\\b/.test(location.search);
  const margin = 1.5;
  const aspect = w / h;
  camera.aspect = aspect;
  camera.updateProjectionMatrix();
  const hFov = 2 * Math.atan(Math.tan(fovRad / 2) * aspect);
  const distForWidth = (sculptureWidth * 0.5 * margin) / Math.tan(hFov / 2);
  const distForHeight = (sculptureHeight * 0.5 * margin) / Math.tan(fovRad / 2);
  camDist = Math.max(distForWidth, distForHeight, isThumb ? 12 : 8);
  // Wheel zoom range: 0.4x to 2.5x the auto-fit distance.
  camDistMin = camDist * 0.4;
  camDistMax = camDist * 2.5;
  camera.position.set(0, 0, camDist);
  camera.lookAt(0, 0, 0);
  renderer.setSize(w, h);
}}
fitToViewport();
window.addEventListener('resize', fitToViewport);
if (typeof ResizeObserver !== 'undefined') {{
  new ResizeObserver(fitToViewport).observe(document.body);
}}

let isDragging = false, lastX = 0;
let lastInteraction = performance.now();
const IDLE_MS = 5000;
const AUTO_YAW_SPEED = 0.0025;

canvas.addEventListener('pointerdown', (e) => {{
  isDragging = true; lastX = e.clientX;
  canvas.setPointerCapture(e.pointerId);
  lastInteraction = performance.now();
}});
canvas.addEventListener('pointermove', (e) => {{
  lastInteraction = performance.now();
  if (!isDragging) return;
  voxelMesh.rotation.y += (e.clientX - lastX) * 0.005;
  lastX = e.clientX;
}});
canvas.addEventListener('pointerup', (e) => {{
  isDragging = false;
  try {{ canvas.releasePointerCapture(e.pointerId); }} catch (_) {{}}
  lastInteraction = performance.now();
}});
canvas.addEventListener('wheel', (e) => {{
  e.preventDefault();
  // Multiplicative zoom: each wheel tick scales distance by a fraction of current camDist.
  const delta = e.deltaY * 0.0015;
  camDist = Math.max(camDistMin, Math.min(camDistMax, camDist + delta * camDist));
  camera.position.set(0, 0, camDist);
  camera.lookAt(0, 0, 0);
  lastInteraction = performance.now();
}}, {{ passive: false }});

let pulse = 0;
function animate() {{
  const now = performance.now();
  pulse += 0.01;
  const s = 1 + Math.sin(pulse) * 0.04;
  voxelMesh.scale.set(s, s, s);
  // Idle auto-rotate: after IDLE_MS without interaction, slowly yaw the voxel.
  // Skip in gallery thumbnails (?thumb=1) — iframe is pointer-events:none so
  // the user can't reset lastInteraction and the voxel would spin forever.
  const isThumbAnim = /[?&]thumb=1\b/.test(location.search);
  if (!isThumbAnim && !isDragging && (now - lastInteraction) > IDLE_MS) {{
    voxelMesh.rotation.y += AUTO_YAW_SPEED;
  }}
  renderer.render(scene, camera);
  requestAnimationFrame(animate);
}}
animate();
</script>
</body>
</html>
"""


def extract_constants(html: str):
    """Extract PALETTE, VOXEL, LAYOUT, META, SEED, skyUrl from a voxel-N.html."""
    out = {}
    for name in ["PALETTE", "VOXEL", "LAYOUT", "META", "SEED"]:
        # Capture up to the statement-terminating ';' (followed by a newline),
        # NOT the first ';' which may appear inside the META content string
        # (e.g. "…por la OMS; en 2018…"). Dropping re.DOTALL + anchoring to
        # the line-ending ';' fixes truncated META.content.
        m = re.search(rf"const {name} = (.+?);\s*(?:\r?\n|$)", html)
        if not m:
            raise ValueError(f"Could not find const {name} in HTML")
        out[name] = m.group(1)
    return out


def extract_sky_url(html: str):
    """Look for textures/sky-XXXX.png reference in the file.

    Looks in multiple places because different generator versions put it
    in different spots:
    - new THREE.TextureLoader().load("textures/sky-XXXX.png")  (old plane approach)
    - const SKY_URL = "textures/sky-XXXX.png"                   (current CSS-BG approach)
    - background-image: url('textures/sky-XXXX.png')            (already-patched files)
    - <meta name="sky-url" content="textures/sky-XXXX.png" />    (autonomous-agent fallback)
    """
    # 1. TextureLoader
    m = re.search(r'load\(["\'](textures/sky-(\d+)\.png)["\']', html)
    if m:
        return m.group(1)
    # 2. SKY_URL const
    m = re.search(r'SKY_URL\s*=\s*["\'](textures/sky-(\d+)\.png)["\']', html)
    if m:
        return m.group(1)
    # 3. background-image already in CSS (idempotent re-run)
    m = re.search(r"url\(['\"]?(textures/sky-(\d+)\.png)['\"]?\)", html)
    if m:
        return m.group(1)
    # 4. <meta name="sky-url" content="textures/sky-XXXX.png"> (added 2026-08-27)
    m = re.search(r'<meta\s+name=["\']sky-url["\']\s+content=["\'](textures/sky-(\d+)\.png)["\']', html)
    if m:
        return m.group(1)
    return None


def main():
    if len(sys.argv) != 2:
        print("Usage: python post-generate-patch.py <voxel-N.html>")
        sys.exit(1)
    path = sys.argv[1]
    if not os.path.isfile(path):
        print(f"File not found: {path}")
        sys.exit(1)
    with open(path, encoding="utf-8") as f:
        html = f.read()
    consts = extract_constants(html)
    sky_url = extract_sky_url(html)
    if not sky_url:
        sys.exit(f"ERROR: no sky-XXXX.png found in {path}; the patcher needs the sky URL "
                 "to build the background-image. Either the candidate has no sky (skyUrl was empty) "
                 "or the file format is unrecognized. Refusing to generate an empty sky-bg div.")
    out = TEMPLATE.format(
        ID_SHORT=consts["META"].split("\"id\":", 1)[1].split("\"", 2)[1][:8] if "\"id\"" in consts["META"] else "t_00000000",
        SKY_URL="https://petrasynthetic.com/huaca/" + (sky_url or ""),
        LABEL="HUACA",
        ACCENT="#888",
        ID_SHORT_UPPER=(consts["META"].split("\"id\":", 1)[1].split("\"", 2)[1][:6] if "\"id\"" in consts["META"] else "T_000000").upper(),
        PALETTE_LITERAL=consts["PALETTE"],
        VOXEL_LITERAL=consts["VOXEL"],
        LAYOUT_LITERAL=consts["LAYOUT"],
        META_LITERAL=consts["META"],
        SEED_LITERAL=consts["SEED"],
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"Patched {path} → canonical Huaca look ({len(out)} bytes)")


if __name__ == "__main__":
    main()
